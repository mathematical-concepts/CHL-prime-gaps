# CLI
# ---------------------------------------------------------------------------


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, help="DS1 generated config JSON")
    parser.add_argument("--root", default=".", help="Repository root")
    parser.add_argument("--blocks", default=None, help="Block spec, for example 1-10")
    parser.add_argument("--filters", default=",".join(FILTERS), help="Comma-separated public filter names")
    parser.add_argument("--Y", type=int, default=None, help="Singular-series truncation; default config pmax")
    parser.add_argument("--log-x", type=float, default=None, help="Local log(x); default log(config start_x)")
    parser.add_argument("--path-cache-file", required=True, help="A02 path-exclusion cache CSV/CSV.GZ")
    parser.add_argument("--workers", type=int, default=1, help="Block workers; 0 means all detected CPUs")
    parser.add_argument("--anchor-tolerance", type=float, default=1e-10)
    parser.add_argument("--hash-inputs", action=argparse.BooleanOptionalAction, default=False)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    telemetry = telemetry_start()
    config_path = Path(args.config)
    root = Path(args.root)
    output_dir = Path(args.output_dir)
    config = load_json(config_path)
    blocks = parse_block_spec(args.blocks, config.get("blocks", list(range(1, 11))))
    filters = parse_csv_list(args.filters)
    unknown = sorted(set(filters) - set(FILTERS))
    if unknown:
        raise ValueError(f"Unknown filters {unknown}; available={sorted(FILTERS)}")
    block_files = resolve_block_files(config, root, blocks)
    Y = int(args.Y if args.Y is not None else config.get("pmax", 47))
    if Y < 2:
        raise ValueError("Y must be >= 2")
    primes = primes_upto(Y)
    start_x = float(config.get("start_x", 1e11))
    log_x = float(args.log_x if args.log_x is not None else math.log(start_x))
    path_cache_path = Path(args.path_cache_file)
    if not path_cache_path.is_file():
        raise FileNotFoundError(path_cache_path)
    workers = (os.cpu_count() or 1) if int(args.workers) == 0 else max(1, int(args.workers))

    input_paths: dict[str, str | Path | None] = {
        "config": config_path,
        "path_cache": path_cache_path,
    }
    for block, path in block_files:
        input_paths[f"parent_wide_B{block:02d}"] = path
    provenance = build_provenance(
        repo_root=root,
        input_paths=input_paths,
        hash_inputs=bool(args.hash_inputs),
    )

    run_config: dict[str, Any] = {
        "phase": "A10_CHL2_FACTOR_COMPATIBILITY",
        "config": str(config_path),
        "root": str(root),
        "blocks": blocks,
        "block_files": [str(path) for _, path in block_files],
        "filters": filters,
        "filter_to_stratum": {name: FILTER_TO_STRATUM[name] for name in filters},
        "Y": Y,
        "truncation_primes": primes,
        "log_x": log_x,
        "path_cache_file": str(path_cache_path),
        "workers_requested": int(args.workers),
        "workers_effective": workers,
        "anchor_tolerance": float(args.anchor_tolerance),
        "support_semantics": "parent_wide_triple_admissible_conditional_by_g1",
        "anchor_semantics": "model_specific_eta_common_empirical_mean_g2_by_block_filter",
        "factor_definitions": {
            "H": "S_Y({0,g2})",
            "R": "S_Y({0,g1,g1+g2})/S_Y({0,g1})",
            "P": "exp[-Omega_Y^path(g1,g2;x)]",
        },
        "models": [asdict(spec) for spec in MODEL_SPECS],
        "provenance": provenance,
    }
    if args.dry_run:
        print(json.dumps(run_config, indent=2, sort_keys=True))
        return 0

    output_dir.mkdir(parents=True, exist_ok=True)
    tasks = [
        (
            block,
            str(path),
            str(path_cache_path),
            tuple(primes),
            tuple(filters),
            float(args.anchor_tolerance),
        )
        for block, path in block_files
    ]
    all_metrics: list[dict[str, Any]] = []
    all_support: list[dict[str, Any]] = []
    block_meta: dict[str, Any] = {}
    if workers > 1 and len(tasks) > 1:
        with ProcessPoolExecutor(max_workers=min(workers, len(tasks))) as executor:
            futures = {executor.submit(_evaluate_block_task, task): int(task[0]) for task in tasks}
            for future in as_completed(futures):
                block = futures[future]
                metrics_rows, support_rows, meta = future.result()
                all_metrics.extend(metrics_rows)
                all_support.extend(support_rows)
                block_meta[f"B{block:02d}"] = meta
                print(f"[A10] completed B{block:02d}", flush=True)
    else:
        for task in tasks:
            block = int(task[0])
            metrics_rows, support_rows, meta = _evaluate_block_task(task)
            all_metrics.extend(metrics_rows)
            all_support.extend(support_rows)
            block_meta[f"B{block:02d}"] = meta
            print(f"[A10] completed B{block:02d}", flush=True)

    metrics = pd.DataFrame(all_metrics, columns=MODEL_METRIC_COLUMNS)
    if metrics.empty:
        raise ValueError("A10 produced no model metrics")
    metrics = metrics.sort_values(["block", "filter", "H", "R", "P"], kind="mergesort").reset_index(drop=True)
    metrics["rank_within_block_filter"] = (
        metrics.groupby(["block", "filter"])["loglik_per_event"]
        .rank(method="min", ascending=False)
        .astype(int)
    )
    support_audit = pd.DataFrame(all_support).sort_values(["block", "filter"], kind="mergesort").reset_index(drop=True)
    expected_block_labels = [f"B{int(block):02d}" for block in blocks]
    missing_cells = build_missing_cells(
        metrics,
        expected_blocks=expected_block_labels,
        expected_filters=filters,
    )
    model_summary = summarize_models(metrics)
    factorial_by_block = build_factorial_effects_by_block(metrics)
    factorial_summary = summarize_factorial_effects(factorial_by_block, model_summary)
    context_by_block = build_context_effects_by_block(metrics)
    context_summary = summarize_context_effects(context_by_block, model_summary)
    gates = build_gate_summary(
        metrics=metrics,
        support_audit=support_audit,
        missing_cells=missing_cells,
        effects_by_block=factorial_by_block,
        context_by_block=context_by_block,
        anchor_tolerance=float(args.anchor_tolerance),
        expected_cells=len(blocks) * len(filters),
    )
    interpretation_summary = write_interpretation(
        output_dir,
        model_summary,
        factorial_summary,
        context_summary,
        gates,
    )

    outputs = {
        "chl2_factor_model_metrics_by_block.csv": metrics,
        "chl2_factor_model_summary.csv": model_summary,
        "chl2_factorial_effects_by_block.csv": factorial_by_block,
        "chl2_factorial_effects_summary.csv": factorial_summary,
        "chl2_factor_context_effects_by_block.csv": context_by_block,
        "chl2_factor_context_effects_summary.csv": context_summary,
        "chl2_factor_missing_cells.csv": missing_cells,
        "chl2_factor_support_audit.csv": support_audit,
    }
    for name, frame in outputs.items():
        frame.to_csv(output_dir / name, index=False)

    output_files = list(outputs) + [
        "chl2_factor_compatibility_interpretation.md",
        "chl2_factor_compatibility_config.json",
        "chl2_factor_compatibility_telemetry.json",
    ]
    run_config.update(
        {
            "output_dir": str(output_dir),
            "output_files": output_files,
            "block_preparation": block_meta,
            "gates": gates,
            "interpretation_summary": interpretation_summary,
        }
    )
    (output_dir / "chl2_factor_compatibility_config.json").write_text(
        json.dumps(run_config, indent=2, sort_keys=True), encoding="utf-8"
    )
    write_telemetry(
        output_dir / "chl2_factor_compatibility_telemetry.json",
        telemetry,
        **run_config,
        model_metric_rows=int(len(metrics)),
        model_summary_rows=int(len(model_summary)),
        factorial_effect_rows=int(len(factorial_by_block)),
        factorial_summary_rows=int(len(factorial_summary)),
        context_effect_rows=int(len(context_by_block)),
        context_summary_rows=int(len(context_summary)),
        support_audit_rows=int(len(support_audit)),
        missing_cell_rows=int(len(missing_cells)),
    )
    print(f"[A10] release gate: {gates['a10_release_gate_pass']}")
    print(f"[A10] wrote outputs to {output_dir}")
    return 0 if gates["a10_release_gate_pass"] else 2


if __name__ == "__main__":
    raise SystemExit(main())
