#!/usr/bin/env python3
"""Public, self-contained CHL2 H/R/P factor-compatibility audit.

This audit evaluates the complete conditional 2^3 design generated by three
multiplicative factors on one common support:

    H(g2)       = S_Y({0,g2})
    R(g2|g1)    = S_Y({0,g1,g1+g2}) / S_Y({0,g1})
    P(g1,g2)    = exp[-Omega_Y^path(g1,g2;x)]

The eight vertices are:

    H R P   model
    0 0 0   ROW_MASK_ETA
    1 0 0   H2_COND_ETA
    0 1 0   CHL1
    0 0 1   PATH_ONLY_ETA
    1 1 0   CG_MARKOV_ETA
    1 0 1   CG_PATH_ETA
    0 1 1   CHL2
    1 1 1   CG_MARKOV_PATH_ETA

Every vertex uses:

* the same parent-wide conditional support by previous gap g1;
* the same triple-admissibility mask;
* the same empirical state masses P_emp(g1);
* the same terminal mean-g2 target, with a model-specific eta chosen only to
  satisfy that common target.

The script has no dependency on ``chl_lab``.  It consumes parent-wide DS1 block
files plus the path-exclusion cache generated by
``paper_audits/chl2_consecutive_exclusion_audit.py`` and writes compact CSV/JSON
outputs under the requested output directory.
"""
