def resolve_block_files(
    config: Mapping[str, Any],
    root: str | Path,
    blocks: Sequence[int],
) -> list[tuple[int, Path]]:
    rootp = Path(root)
    input_dir = rootp / str(config.get("input_dir", ""))
    blocks_dir = input_dir / str(config.get("blocks_dir", "blocks"))
    pattern = str(
        config.get("block_glob")
        or config.get("block_pattern")
        or "parent_wide_B{block:02d}.csv.gz"
    )
    resolved: list[tuple[int, Path]] = []
    for block in blocks:
        candidates: list[Path] = []
        try:
            candidates.append(blocks_dir / pattern.format(block=int(block)))
        except Exception:
            pass
        candidates.extend(
            [
                blocks_dir / f"parent_wide_B{int(block):02d}.csv.gz",
                blocks_dir / f"v46t12_ds_pilot_parent_wide_B{int(block):02d}.csv.gz",
                input_dir / f"parent_wide_B{int(block):02d}.csv.gz",
            ]
        )
        seen: set[str] = set()
        unique_candidates: list[Path] = []
        for candidate in candidates:
            key = str(candidate)
            if key not in seen:
                unique_candidates.append(candidate)
                seen.add(key)
        candidates = unique_candidates
        found = next((p for p in candidates if p.is_file()), None)
        if found is None:
            tried = "\n  ".join(str(p) for p in candidates)
            raise FileNotFoundError(
                f"Could not resolve parent-wide file for block B{int(block):02d}. Tried:\n  {tried}"
            )
        resolved.append((int(block), found))
    return resolved


def support_sha256(df: pd.DataFrame) -> str:
    keys = (
        df[["g1", "g2"]]
        .drop_duplicates()
        .sort_values(["g1", "g2"], kind="mergesort")
        .itertuples(index=False, name=None)
    )
    digest = hashlib.sha256()
    for g1, g2 in keys:
        digest.update(f"{int(g1)},{int(g2)}\n".encode("ascii"))
    return digest.hexdigest()


def sha256_file(path: str | Path, chunk_size: int = 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(int(chunk_size)), b""):
            digest.update(chunk)
    return digest.hexdigest()


def file_provenance(path: str | Path, *, hash_content: bool) -> dict[str, Any]:
    p = Path(path)
    record: dict[str, Any] = {"path": str(p), "exists": bool(p.is_file())}
    if not p.is_file():
        return record
    stat = p.stat()
    record.update(
        {
            "size_bytes": int(stat.st_size),
            "mtime_ns": int(stat.st_mtime_ns),
            "sha256": sha256_file(p) if hash_content else None,
        }
    )
    return record


def git_provenance(repo_root: str | Path) -> dict[str, Any]:
    root = Path(repo_root)

    def run_git(*args: str) -> str | None:
        try:
            proc = subprocess.run(
                ["git", "-C", str(root), *args],
                check=False,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
            )
        except OSError:
            return None
        if proc.returncode != 0:
            return None
        return proc.stdout.strip()

    commit = run_git("rev-parse", "HEAD")
    branch = run_git("rev-parse", "--abbrev-ref", "HEAD")
    describe = run_git("describe", "--tags", "--always", "--dirty")
    status = run_git("status", "--porcelain", "--untracked-files=no")
    tracked_changes = None if status is None else ([x for x in status.splitlines() if x] if status else [])
    return {
        "repo_root": str(root),
        "available": commit is not None,
        "commit": commit,
        "branch": branch,
        "describe": describe,
        "tracked_worktree_clean": None if tracked_changes is None else not bool(tracked_changes),
        "tracked_changes": tracked_changes,
    }


def build_provenance(
    *,
    repo_root: str | Path,
    input_paths: Mapping[str, str | Path | None],
    hash_inputs: bool,
) -> dict[str, Any]:
    inputs = {
        str(label): file_provenance(path, hash_content=bool(hash_inputs))
        for label, path in sorted(input_paths.items())
        if path not in (None, "")
    }
    return {
        "schema": "chl-release-provenance@1",
        "script": file_provenance(Path(__file__).resolve(), hash_content=True),
        "git": git_provenance(repo_root),
        "input_hashes_enabled": bool(hash_inputs),
        "inputs": inputs,
    }


