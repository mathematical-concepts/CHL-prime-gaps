def singular_logs_for_pairs(
    g1: np.ndarray,
    g2: np.ndarray,
    primes: Sequence[int],
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Return log S2(g1), log S3(g1,g2), log R, admissible mask."""
    g1 = np.asarray(g1, dtype=np.int64)
    g2 = np.asarray(g2, dtype=np.int64)
    total = g1 + g2
    n = len(g1)
    log_s2 = np.zeros(n, dtype=np.float64)
    log_s3 = np.zeros(n, dtype=np.float64)
    admissible = np.ones(n, dtype=bool)

    for p in primes:
        pf = float(p)
        g1m = g1 % p
        tm = total % p
        nu2 = np.where(g1m == 0, 1.0, 2.0)
        nu3 = np.ones(n, dtype=np.float64)
        nu3 += g1m != 0
        nu3 += (tm != 0) & (tm != g1m)
        f2 = (1.0 - nu2 / pf) / ((1.0 - 1.0 / pf) ** 2)
        f3 = (1.0 - nu3 / pf) / ((1.0 - 1.0 / pf) ** 3)
        valid = f3 > 0.0
        admissible &= valid
        with np.errstate(divide="ignore", invalid="ignore"):
            log_s2 += np.where(f2 > 0.0, np.log(f2), -np.inf)
            log_s3 += np.where(valid, np.log(f3), -np.inf)

    log_ratio = log_s3 - log_s2
    log_ratio[~admissible] = -np.inf
    return log_s2, log_s3, log_ratio, admissible


def singular_log_s2_gap(g_values: np.ndarray, primes: Sequence[int]) -> tuple[np.ndarray, np.ndarray]:
    g = np.asarray(g_values, dtype=np.int64)
    log_s2 = np.zeros(len(g), dtype=np.float64)
    admissible = np.ones(len(g), dtype=bool)
    for p in primes:
        pf = float(p)
        gm = g % p
        nu2 = np.where(gm == 0, 1.0, 2.0)
        f2 = (1.0 - nu2 / pf) / ((1.0 - 1.0 / pf) ** 2)
        valid = f2 > 0.0
        admissible &= valid
        with np.errstate(divide="ignore", invalid="ignore"):
            log_s2 += np.where(valid, np.log(f2), -np.inf)
    log_s2[~admissible] = -np.inf
    return log_s2, admissible


def load_path_cache(path: str | Path) -> pd.DataFrame:
    p = Path(path)
    if not p.is_file():
        raise FileNotFoundError(p)
    df = pd.read_csv(p)
    required = {"g1", "g2"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Path cache {p} missing required columns {sorted(missing)}")

    out = df[["g1", "g2"]].copy()
    if "logE_path_exclusion" in df.columns:
        out["_log_P"] = pd.to_numeric(df["logE_path_exclusion"], errors="coerce")
    elif "omega_path_exclusion" in df.columns:
        out["_log_P"] = -pd.to_numeric(df["omega_path_exclusion"], errors="coerce")
    elif "omega_path" in df.columns:
        out["_log_P"] = -pd.to_numeric(df["omega_path"], errors="coerce")
    else:
        raise ValueError(
            f"Path cache {p} needs logE_path_exclusion, omega_path_exclusion, or omega_path"
        )

    out["g1"] = pd.to_numeric(out["g1"], errors="raise").astype(np.int64)
    out["g2"] = pd.to_numeric(out["g2"], errors="raise").astype(np.int64)
    if out["_log_P"].isna().any():
        raise ValueError(f"Path cache {p} contains non-numeric path values")

    duplicated = out.duplicated(["g1", "g2"], keep=False)
    if duplicated.any():
        checks = out.loc[duplicated].groupby(["g1", "g2"])["_log_P"].agg(["min", "max"])
        conflicting = checks[(checks["max"] - checks["min"]).abs() > 1e-14]
        if not conflicting.empty:
            raise ValueError(
                f"Path cache {p} contains conflicting duplicate keys: "
                f"{conflicting.head().reset_index().to_dict('records')}"
            )
        out = out.drop_duplicates(["g1", "g2"], keep="first")
    return out.reset_index(drop=True)


