def context_effect_definitions() -> list[dict[str, Any]]:
    definitions: list[dict[str, Any]] = []
    factor_index = {"H": 0, "R": 1, "P": 2}
    for factor in FACTOR_NAMES:
        idx = factor_index[factor]
        other = [x for x in FACTOR_NAMES if x != factor]
        for level_a in (0, 1):
            for level_b in (0, 1):
                low = [0, 0, 0]
                high = [0, 0, 0]
                low[idx] = 0
                high[idx] = 1
                low[factor_index[other[0]]] = high[factor_index[other[0]]] = level_a
                low[factor_index[other[1]]] = high[factor_index[other[1]]] = level_b
                low_sig = tuple(low)
                high_sig = tuple(high)
                definitions.append(
                    {
                        "factor": factor,
                        "context": f"{other[0]}={level_a};{other[1]}={level_b}",
                        "other_factor_1": other[0],
                        "other_level_1": level_a,
                        "other_factor_2": other[1],
                        "other_level_2": level_b,
                        "low_signature": low_sig,
                        "high_signature": high_sig,
                        "model_low": MODEL_BY_SIGNATURE[low_sig].name,
                        "model_high": MODEL_BY_SIGNATURE[high_sig].name,
                    }
                )
    return definitions


CONTEXT_EFFECTS = context_effect_definitions()


