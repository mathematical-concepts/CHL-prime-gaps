def _effect_label(value: float, tolerance: float = 1e-12) -> str:
    if value > tolerance:
        return "positive/synergistic"
    if value < -tolerance:
        return "negative/antagonistic"
    return "near-zero"


def build_gate_summary(
    *,
    metrics: pd.DataFrame,
    support_audit: pd.DataFrame,
    missing_cells: pd.DataFrame,
    effects_by_block: pd.DataFrame,
    context_by_block: pd.DataFrame,
    anchor_tolerance: float,
    expected_cells: int | None = None,
) -> dict[str, Any]:
    actual_cells = int(support_audit.shape[0])
    cells = int(actual_cells if expected_cells is None else expected_cells)
    expected_metric_rows = cells * 8
    expected_effect_rows = cells * 7
    expected_context_rows = cells * 12
    complete = bool(
        missing_cells.empty
        and actual_cells == cells
        and len(metrics) == expected_metric_rows
    )
    common_support = bool(
        not support_audit.empty
        and support_audit["common_support_gate_pass"].astype(bool).all()
    )
    anchor_max = float(metrics["anchor_abs_error"].max()) if not metrics.empty else math.inf
    anchor_pass = bool(anchor_max <= float(anchor_tolerance) * 10.0)
    effects_complete = bool(len(effects_by_block) == expected_effect_rows)
    contexts_complete = bool(len(context_by_block) == expected_context_rows)
    finite_metrics = bool(
        not metrics.empty
        and np.isfinite(
            metrics[
                [
                    "loglik_sum",
                    "loglik_per_event",
                    "conditional_kl",
                    "eta",
                    "mean_g2_model",
                ]
            ].to_numpy(dtype=float)
        ).all()
    )
    gate_pass = bool(
        complete
        and common_support
        and anchor_pass
        and effects_complete
        and contexts_complete
        and finite_metrics
    )
    return {
        "expected_block_filter_cells": cells,
        "actual_block_filter_cells": actual_cells,
        "expected_model_metric_rows": expected_metric_rows,
        "actual_model_metric_rows": int(len(metrics)),
        "expected_factorial_effect_rows": expected_effect_rows,
        "actual_factorial_effect_rows": int(len(effects_by_block)),
        "expected_context_effect_rows": expected_context_rows,
        "actual_context_effect_rows": int(len(context_by_block)),
        "missing_cell_rows": int(len(missing_cells)),
        "complete_factorial_cube_gate_pass": complete,
        "common_support_gate_pass": common_support,
        "anchor_max_abs_error": anchor_max,
        "anchor_tolerance": float(anchor_tolerance),
        "terminal_anchor_gate_pass": anchor_pass,
        "factorial_effects_complete_gate_pass": effects_complete,
        "context_effects_complete_gate_pass": contexts_complete,
        "finite_metrics_gate_pass": finite_metrics,
        "a10_release_gate_pass": gate_pass,
    }


