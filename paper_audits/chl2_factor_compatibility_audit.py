def read_parent_wide_block(path: str | Path) -> pd.DataFrame:
    df = pd.read_csv(path)
    required = {"g1", "g2", "H"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"{path} missing required columns {sorted(missing)}")
    out = df[["g1", "g2", "H"]].copy()
    out["g1"] = pd.to_numeric(out["g1"], errors="raise").astype(np.int64)
    out["g2"] = pd.to_numeric(out["g2"], errors="raise").astype(np.int64)
    out["H"] = pd.to_numeric(out["H"], errors="raise").astype(np.float64)
    if (out["H"] < 0).any():
        raise ValueError(f"{path} contains negative H counts")
    if out.duplicated(["g1", "g2"]).any():
        out = out.groupby(["g1", "g2"], as_index=False, sort=True).agg(H=("H", "sum"))
    out["max_g"] = np.maximum(out["g1"].to_numpy(), out["g2"].to_numpy())
    return out.sort_values(["g1", "g2"], kind="mergesort").reset_index(drop=True)


def prepare_block_factors(
    block_df: pd.DataFrame,
    primes: Sequence[int],
    path_cache: pd.DataFrame,
    *,
    block: int,
) -> tuple[pd.DataFrame, dict[str, Any]]:
    df = block_df.copy()
    _, _, log_r, adm3 = singular_logs_for_pairs(
        df["g1"].to_numpy(dtype=np.int64),
        df["g2"].to_numpy(dtype=np.int64),
        primes,
    )
    unique_g2 = np.array(sorted(df["g2"].astype(int).unique()), dtype=np.int64)
    log_h_unique, adm2 = singular_log_s2_gap(unique_g2, primes)
    h_map = {int(g): float(v) for g, v in zip(unique_g2, log_h_unique)}
    h_adm_map = {int(g): bool(v) for g, v in zip(unique_g2, adm2)}
    df["_log_R"] = log_r
    df["_adm3"] = adm3
    df["_log_H"] = df["g2"].map(h_map).astype(float)
    df["_adm2_g2"] = df["g2"].map(h_adm_map).astype(bool)
    df = df.merge(path_cache, on=["g1", "g2"], how="left", validate="many_to_one")

    observed_inadmissible = int(((df["H"] > 0) & (~df["_adm3"])).sum())
    if observed_inadmissible:
        bad = df.loc[(df["H"] > 0) & (~df["_adm3"]), ["g1", "g2", "H"]].head()
        raise ValueError(
            f"B{int(block):02d} contains {observed_inadmissible} observed triple-inadmissible rows: "
            f"{bad.to_dict('records')}"
        )

    admissible_missing_path = int((df["_adm3"] & df["_log_P"].isna()).sum())
    if admissible_missing_path:
        bad = df.loc[df["_adm3"] & df["_log_P"].isna(), ["g1", "g2"]].head()
        raise ValueError(
            f"B{int(block):02d} has {admissible_missing_path} admissible rows missing from path cache: "
            f"{bad.to_dict('records')}"
        )

    common = (
        df["_adm3"].to_numpy(dtype=bool)
        & df["_adm2_g2"].to_numpy(dtype=bool)
        & np.isfinite(df["_log_R"].to_numpy(dtype=float))
        & np.isfinite(df["_log_H"].to_numpy(dtype=float))
        & np.isfinite(df["_log_P"].to_numpy(dtype=float))
    )
    outside_observed = int(((df["H"] > 0).to_numpy(dtype=bool) & (~common)).sum())
    if outside_observed:
        bad = df.loc[(df["H"] > 0).to_numpy(dtype=bool) & (~common), ["g1", "g2", "H"]].head()
        raise ValueError(
            f"B{int(block):02d} has {outside_observed} observed rows outside the common H/R/P support: "
            f"{bad.to_dict('records')}"
        )
    df = df.loc[common].reset_index(drop=True)
    meta = {
        "raw_support_rows": int(len(block_df)),
        "common_support_rows": int(len(df)),
        "triple_inadmissible_rows_dropped": int(len(block_df) - int(np.sum(adm3))),
        "observed_inadmissible_rows": observed_inadmissible,
        "admissible_path_cache_missing_rows": admissible_missing_path,
    }
    return df, meta


def evaluate_block(
    *,
    block: int,
    block_path: str | Path,
    path_cache_path: str | Path,
    primes: Sequence[int],
    filters: Sequence[str],
    anchor_tolerance: float,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], dict[str, Any]]:
    block_df = read_parent_wide_block(block_path)
    path_cache = load_path_cache(path_cache_path)
    prepared, block_meta = prepare_block_factors(block_df, primes, path_cache, block=block)

    metrics: list[dict[str, Any]] = []
    support_rows: list[dict[str, Any]] = []
    for filter_name in filters:
        mask = FILTERS[filter_name](prepared["max_g"].to_numpy(dtype=np.int64))
        cell = prepared.loc[mask].copy().reset_index(drop=True)
        if cell.empty or float(cell["H"].sum()) <= 0:
            continue
        observed_states = sorted(cell.loc[cell["H"] > 0, "g1"].astype(int).unique())
        if not observed_states:
            continue
        candidates_per_state = cell.groupby("g1").size()
        missing_observed_states = [state for state in observed_states if int(state) not in candidates_per_state.index]
        if missing_observed_states:  # pragma: no cover - defensive
            raise ValueError(
                f"B{block:02d}/{filter_name} missing conditional support for observed g1 states "
                f"{missing_observed_states[:8]}"
            )
        s_hash = support_sha256(cell)
        model_rows = [
            evaluate_model(
                cell,
                spec,
                anchor_tolerance=anchor_tolerance,
                support_hash=s_hash,
                block=block,
                filter_name=filter_name,
            )
            for spec in MODEL_SPECS
        ]
        metrics.extend(model_rows)
        target_values = {round(float(row["target_mean_g2"]), 12) for row in model_rows}
        support_hashes = {str(row["support_sha256"]) for row in model_rows}
        anchor_max = max(float(row["anchor_abs_error"]) for row in model_rows)
        support_rows.append(
            {
                "block": f"B{int(block):02d}",
                "filter": filter_name,
                "stratum": FILTER_TO_STRATUM[filter_name],
                "support_semantics": "parent_wide_triple_admissible_conditional_by_g1",
                "support_sha256": s_hash,
                "support_rows": int(len(cell)),
                "observed_rows": int((cell["H"] > 0).sum()),
                "g1_states_observed": int(len(observed_states)),
                "min_candidates_per_g1": int(candidates_per_state.loc[observed_states].min()),
                "max_candidates_per_g1": int(candidates_per_state.loc[observed_states].max()),
                "n_events": float(cell["H"].sum()),
                "target_mean_g2": float(model_rows[0]["target_mean_g2"]),
                "model_vertices": int(len(model_rows)),
                "unique_support_hashes_across_vertices": int(len(support_hashes)),
                "unique_targets_across_vertices": int(len(target_values)),
                "anchor_max_abs_error": float(anchor_max),
                "common_support_gate_pass": bool(
                    len(model_rows) == 8 and len(support_hashes) == 1 and len(target_values) == 1
                ),
                "anchor_gate_pass": bool(anchor_max <= float(anchor_tolerance) * 10.0),
            }
        )
    return metrics, support_rows, block_meta


def _evaluate_block_task(task: tuple[Any, ...]):
    block, block_path, cache_path, primes, filters, anchor_tolerance = task
    return evaluate_block(
        block=int(block),
        block_path=block_path,
        path_cache_path=cache_path,
        primes=tuple(int(p) for p in primes),
        filters=tuple(str(x) for x in filters),
        anchor_tolerance=float(anchor_tolerance),
    )


