def parse_block_spec(text: str | None, default: Sequence[int]) -> list[int]:
    if not text:
        return sorted(dict.fromkeys(int(x) for x in default))
    out: list[int] = []
    for part in str(text).split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            out.extend(range(int(a), int(b) + 1))
        else:
            out.append(int(part))
    return sorted(dict.fromkeys(out))


def parse_csv_list(text: str) -> list[str]:
    return list(dict.fromkeys(part.strip() for part in str(text).split(",") if part.strip()))


def primes_upto(n: int) -> list[int]:
    n = int(n)
    if n < 2:
        return []
    sieve = bytearray(b"\x01") * (n + 1)
    sieve[0:2] = b"\x00\x00"
    for p in range(2, int(n**0.5) + 1):
        if sieve[p]:
            start = p * p
            sieve[start : n + 1 : p] = b"\x00" * (((n - start) // p) + 1)
    return [i for i in range(2, n + 1) if sieve[i]]


def logsumexp(values: np.ndarray) -> float:
    a = np.asarray(values, dtype=np.float64)
    if a.size == 0:
        return -math.inf
    m = float(np.max(a))
    if not math.isfinite(m):
        return -math.inf
    return float(m + math.log(float(np.exp(a - m).sum())))


